local mod = dmhub.GetModLoading()

-- The torn-note puzzle type: an image (or a typed note) torn into irregular
-- pieces scattered on a table. Players drag pieces (or click a piece, then click
-- where it goes). A piece dropped against a true neighbour joins it and tape is
-- laid across the seam; joined pieces move as one. Registered with the puzzle
-- framework (PuzzleFramework.lua), which owns storage, holds, the solved banner,
-- the chat line and the Director controls.
--
-- Also the old [[tornpuzzle:Name]] journal tag: it now shows a framework puzzle,
-- copying its setup and saved table across the first time it is opened.
--
-- Shapes come from TornPuzzleShapes.lua and the tornMask* image resources, both
-- generated by tools/tornpuzzle/make_torn_masks.py. Design briefs:
-- principlesnstuff/torn-puzzle-brief.md and puzzle-lock-brief.md (Lisa's machine).

--Every position is in "image units": 1 = the image's full width (x) or full
--height (y), measured from the table's top-left. The table is TABLE_SCALE images
--wide and tall, which leaves room around the note to scatter pieces.
local TABLE_SCALE = 1.7

--How close (image units, each axis) a dropped group must land to where a
--neighbour expects it before the two join.
local SNAP_DISTANCE = 0.05

--Loose pieces lie tilted up to this many degrees, like dropped paper.
local MAX_TILT = 8

--The image id of one of this mod's image resources (the tornMask* atlases).
--Resources uploaded since storage moved to R2 have URL-form ids, and mod.images
--wraps them as "md5:<url>", which does not load; the bare URL loads for every
--player. Harmless once the engine stops adding the prefix.
---@param name string
---@return string|nil
local function ResourceImage(name)
    local id = mod.images[name]
    if type(id) == "string" and string.sub(id, 1, 4) == "md5:" and string.find(id, "://", 1, true) ~= nil then
        return string.sub(id, 5)
    end
    return id
end

--Typed notes: each client renders the note's text onto paper locally (no upload)
--and the puzzle tears that image like any other. A preset is paper colour, font and
--ink together, so the Director picks a look rather than mixing colours.
--charEm is the font's average character width in ems, used to estimate wrapping.
---@class TornNotePaper
---@field name string
---@field paper string
---@field ink string
---@field font string
---@field charEm number
---@field align string

---@type table<string, TornNotePaper>
local NOTE_PAPERS = {
    letter = { name = "Letter", paper = "#e8dcc0", ink = "#3a2a1a", font = "Berling", charEm = 0.5, align = "left" },
    typed = { name = "Typed", paper = "#fafaf7", ink = "#1b1b1b", font = "Courier", charEm = 0.6, align = "left" },
    proclamation = { name = "Proclamation", paper = "#e8dcc0", ink = "#3a2a1a", font = "Book", charEm = 0.68, align = "center" },
    ransom = { name = "Ransom", paper = "#c9b48a", ink = "#2b1d10", font = "Colvillain", charEm = 0.6, align = "center" },
}
local NOTE_PAPER_ORDER = { "letter", "typed", "proclamation", "ransom" }

--A note is always this wide (UI units); its height follows the text.
local NOTE_WIDTH = 600
local NOTE_PADDING = 48
local NOTE_FONT_SIZE = 30
local NOTE_LINE_HEIGHT = 1.35
--Rendered at this many pixels per UI unit so the text stays crisp on the table.
local NOTE_RENDER_SCALE = 2

--True when this client's engine can render panels to images (gui.RenderToImage,
--added in 0.0.880). Older clients get a message instead of a blank table.
---@return boolean
local function NotesSupported()
    local ok, fn = pcall(function()
        ---@diagnostic disable-next-line: undefined-field -- engine API newer than the Definitions stubs
        return gui.RenderToImage
    end)
    return ok and fn ~= nil
end

--The note's size and font size. Wrapping is ESTIMATED from character counts rather
--than measured, so every client computes the same shape from the same text: never
--shorter than a 3:2 card, never taller than the puzzle's 2.5x cap (past that the
--font shrinks until it fits).
---@param text string
---@param paper TornNotePaper
---@return number width, number height, number fontSize
local function NoteLayout(text, paper)
    local textWidth = NOTE_WIDTH - NOTE_PADDING * 2
    local maxHeight = NOTE_WIDTH * 2.5
    local fontSize = NOTE_FONT_SIZE
    local textHeight = 0
    for _ = 1, 4 do
        local lines = 0
        for paragraph in string.gmatch(text .. "\n", "([^\n]*)\n") do
            local width = #paragraph * fontSize * paper.charEm
            lines = lines + math.max(1, math.ceil(width / textWidth))
        end
        textHeight = lines * fontSize * NOTE_LINE_HEIGHT
        if textHeight + NOTE_PADDING * 2 <= maxHeight then
            break
        end
        fontSize = fontSize * math.sqrt((maxHeight - NOTE_PADDING * 2) / textHeight)
    end
    local height = math.min(maxHeight, math.max(NOTE_WIDTH * 2 / 3, textHeight + NOTE_PADDING * 2))
    return NOTE_WIDTH, math.floor(height), fontSize
end

local PIECE_OPTIONS = { 4, 6, 9, 12 }
local PRETAPE_FRACTION = { none = 0, few = 0.2, half = 0.5 }

---@class TornGroup
---@field x number origin x: where the image's left edge would sit, image units
---@field y number origin y: where the image's top edge would sit, image units
---@field tilt number degrees; only drawn on single-piece groups
---@field z integer draw order; higher is on top

---@class TornBoard
---@field n integer piece count
---@field variant integer which tear pattern in TornPuzzleShapes[n]
---@field mirror boolean pattern flipped left-right for variety
---@field member integer[] piece index -> id of the group it belongs to
---@field groups table<integer, TornGroup>
---@field done boolean

---@class TornPiece
---@field bbox number[] x1, y1, x2, y2 in image units (y down)
---@field mask any core.Vector4 rect of this piece's mask in its atlas
---@field poly number[] flat x, y outline in image units, for hit-testing

---@class TornSeam
---@field a integer
---@field b integer
---@field mid number[]
---@field angle number degrees in image units (y down)

---@class TornShape
---@field pieces TornPiece[]
---@field seams TornSeam[]
---@field atlas string|nil image id of the mask atlas


---@param random fun(k: integer): integer
---@return number 0..1
local function RandomFraction(random)
    return (random(10001) - 1) / 10000
end

local g_shapeCache = {}

--Piece and seam geometry for one board, with the left-right mirror applied.
--Mirroring flips the outline and the mask; the image itself is never flipped.
---@param board TornBoard
---@return TornShape
local function ShapeFor(board)
    local cacheKey = string.format("%d:%d:%s", board.n, board.variant, tostring(board.mirror))
    local cached = g_shapeCache[cacheKey]
    if cached ~= nil then
        return cached
    end

    local set = TornPuzzleShapes[board.n]
    local variant = set.variants[board.variant] or set.variants[1]
    local shape = { pieces = {}, seams = {}, atlas = ResourceImage(set.atlas) }

    for i, p in ipairs(variant.pieces) do
        local b, a = p.bbox, p.atlas
        local poly = {}
        if board.mirror then
            for j = 1, #p.poly, 2 do
                poly[j] = 1 - p.poly[j]
                poly[j + 1] = p.poly[j + 1]
            end
            shape.pieces[i] = {
                bbox = { 1 - b[3], b[2], 1 - b[1], b[4] },
                --swapping the x ends of the rect flips the mask horizontally.
                mask = core.Vector4(a[3], a[2], a[1], a[4]),
                poly = poly,
            }
        else
            for j = 1, #p.poly do
                poly[j] = p.poly[j]
            end
            shape.pieces[i] = {
                bbox = { b[1], b[2], b[3], b[4] },
                mask = core.Vector4(a[1], a[2], a[3], a[4]),
                poly = poly,
            }
        end
    end

    for i, s in ipairs(variant.seams) do
        if board.mirror then
            shape.seams[i] = { a = s.a, b = s.b, mid = { 1 - s.mid[1], s.mid[2] }, angle = 180 - s.angle }
        else
            shape.seams[i] = { a = s.a, b = s.b, mid = { s.mid[1], s.mid[2] }, angle = s.angle }
        end
    end

    g_shapeCache[cacheKey] = shape
    return shape
end

--The rectangle (image units, relative to the group origin) covered by a group.
---@param board TornBoard
---@param shape TornShape
---@param groupId integer
---@return number x1, number y1, number x2, number y2
local function GroupBounds(board, shape, groupId)
    local x1, y1, x2, y2 = math.huge, math.huge, -math.huge, -math.huge
    for k, g in ipairs(board.member) do
        if g == groupId then
            local b = shape.pieces[k].bbox
            x1, y1 = math.min(x1, b[1]), math.min(y1, b[2])
            x2, y2 = math.max(x2, b[3]), math.max(y2, b[4])
        end
    end
    return x1, y1, x2, y2
end

--Keep a group's whole footprint on the table.
---@param board TornBoard
---@param shape TornShape
---@param groupId integer
local function ClampGroup(board, shape, groupId)
    local group = board.groups[groupId]
    local x1, y1, x2, y2 = GroupBounds(board, shape, groupId)
    group.x = math.max(-x1, math.min(TABLE_SCALE - x2, group.x))
    group.y = math.max(-y1, math.min(TABLE_SCALE - y2, group.y))
end

---@param board TornBoard
---@return integer
local function GroupCount(board)
    local count = 0
    for _ in pairs(board.groups) do
        count = count + 1
    end
    return count
end

---@param board TornBoard
---@return integer
local function TopZ(board)
    local z = 0
    for _, group in pairs(board.groups) do
        z = math.max(z, group.z)
    end
    return z
end

--Every piece of group `from` joins group `into`.
---@param board TornBoard
---@param from integer
---@param into integer
local function MergeGroups(board, from, into)
    for k, g in ipairs(board.member) do
        if g == from then
            board.member[k] = into
        end
    end
    board.groups[from] = nil
    board.groups[into].tilt = 0
end

--Tear a fresh board: pick a pattern, pre-tape some seams, scatter the groups.
---@param n integer
---@param pretape string
---@param random fun(k: integer): integer
---@return TornBoard
local function Tear(n, pretape, random)
    local set = TornPuzzleShapes[n]
    ---@type TornBoard
    local board = {
        n = n,
        variant = random(#set.variants),
        mirror = random(2) == 2,
        member = {},
        groups = {},
        done = false,
    }
    for k = 1, n do
        board.member[k] = k
        board.groups[k] = { x = 0, y = 0, tilt = 0, z = k }
    end

    local shape = ShapeFor(board)
    local order = {}
    for i = 1, #shape.seams do
        order[i] = i
    end
    for i = #order, 2, -1 do
        local j = random(i)
        order[i], order[j] = order[j], order[i]
    end
    local toTape = math.floor((PRETAPE_FRACTION[pretape] or 0) * #shape.seams + 0.5)
    for i = 1, toTape do
        local seam = shape.seams[order[i]]
        local ga, gb = board.member[seam.a], board.member[seam.b]
        if ga ~= gb then
            MergeGroups(board, gb, ga)
        end
    end
    --taping every seam would hand over a finished note; leave the last one loose.
    if GroupCount(board) == 1 and n > 1 then
        local seam = shape.seams[order[1]]
        board.member[seam.b] = seam.b
        board.groups[seam.b] = { x = 0, y = 0, tilt = 0, z = n + 1 }
    end

    for id, group in pairs(board.groups) do
        local x1, y1, x2, y2 = GroupBounds(board, shape, id)
        group.x = -x1 + RandomFraction(random) * (TABLE_SCALE - (x2 - x1))
        group.y = -y1 + RandomFraction(random) * (TABLE_SCALE - (y2 - y1))
        local single = 0
        for _, g in ipairs(board.member) do
            if g == id then
                single = single + 1
            end
        end
        if single == 1 then
            group.tilt = random(MAX_TILT * 2 + 1) - MAX_TILT - 1
        end
    end
    return board
end

---@param n integer
---@return TornBoard
local function SolvedBoard(n)
    ---@type TornBoard
    local board = { n = n, variant = 1, mirror = false, member = {}, groups = {}, done = true }
    for k = 1, n do
        board.member[k] = 1
    end
    local offset = (TABLE_SCALE - 1) / 2
    board.groups[1] = { x = offset, y = offset, tilt = 0, z = 1 }
    return board
end


--Boards travel as short strings rather than nested lists: a Lua list is uploaded
--whole, and a string arrives exactly as written.
---@param board TornBoard
---@return table
local function Encode(board)
    local groups = {}
    for id, g in pairs(board.groups) do
        groups[#groups + 1] = string.format("%d:%.4f:%.4f:%d:%d", id, g.x, g.y, round(g.tilt), g.z)
    end
    return {
        n = board.n,
        variant = board.variant,
        mirror = board.mirror,
        member = table.concat(board.member, ","),
        groups = table.concat(groups, ";"),
        done = board.done,
    }
end

---@param entry any
---@param n integer
---@return TornBoard|nil
local function Decode(entry, n)
    if type(entry) ~= "table" or entry.n ~= n or type(entry.member) ~= "string" or type(entry.groups) ~= "string" then
        return nil
    end
    local set = TornPuzzleShapes[n]
    local variant = math.tointeger(entry.variant)
    if set == nil or variant == nil or set.variants[variant] == nil then
        return nil
    end
    ---@type TornBoard
    local board = {
        n = n,
        variant = variant,
        mirror = entry.mirror == true,
        member = {},
        groups = {},
        done = entry.done == true,
    }
    for part in string.gmatch(entry.groups, "[^;]+") do
        local id, x, y, tilt, z = string.match(part, "^(%d+):([%-%d%.]+):([%-%d%.]+):([%-%d]+):(%d+)$")
        if id ~= nil then
            board.groups[math.tointeger(tonumber(id)) or 0] = {
                x = tonumber(x) or 0,
                y = tonumber(y) or 0,
                tilt = tonumber(tilt) or 0,
                z = math.tointeger(tonumber(z)) or 0,
            }
        end
    end
    for part in string.gmatch(entry.member, "[^,]+") do
        local g = math.tointeger(tonumber(part))
        if g == nil or board.groups[g] == nil then
            return nil
        end
        board.member[#board.member + 1] = g
    end
    if #board.member ~= n then
        return nil
    end
    return board
end

