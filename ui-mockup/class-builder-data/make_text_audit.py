"""Turns TEXT_ONLY_FEATURES_AUDIT.md into ../class-builder/text-audit.js, so the class builder can say
on each text-only feature what the audit found (applied elsewhere, buildable, needs a block, story text).
Run from this folder after the audit changes: python make_text_audit.py"""
import json, re
feats = json.load(open('text-only-features.json'))
rows = []
for line in open('TEXT_ONLY_FEATURES_AUDIT.md', encoding='utf-8'):
    cells = [c.strip() for c in line.strip().strip('|').split('|')]
    if len(cells) == 5 and cells[3] in ('A', 'B', 'C', 'D', 'Unsure'):
        rows.append(cells)
def lane_of(level):
    m = re.match(r'1 \(slow start, enc\. (\d)\)', level)
    return 'tutoriallevel-' + m.group(1) if m else 'level-' + re.match(r'\d+', level).group(0)
clean = lambda t: re.sub(r'[*`]', '', t)
out, used = {}, set()
for cls, level, feat, cat, why in rows:
    lane = lane_of(level)
    key = cls + '|' + lane + '|' + feat
    if not any(f['class'] == cls and f['lane'] == lane and f['feature'].strip() == feat for f in feats):
        print('no match:', key); continue
    out[key] = {'cat': cat, 'why': clean(why)}
open('../class-builder/text-audit.js', 'w').write('/* Generated by class-builder-data/make_text_audit.py from TEXT_ONLY_FEATURES_AUDIT.md. */\nwindow.CB_TEXT_AUDIT = ' + json.dumps(out, ensure_ascii=False, indent=0) + ';\n')
print(len(rows), 'rows,', len(out), 'written')
