"""Generate typed overloads for the data-table getters from the codex's own declarations.

    python tools/typing/gen_table_overloads.py           # rewrite the generated blocks
    python tools/typing/gen_table_overloads.py --check   # exit 1 if they are stale

Run from the codex root (any directory works; paths are found from this file). Needs only
this repository: when the codex sits inside a DMHub engine checkout, the engine's copy of
core-definitions is updated as well.

`dmhub.GetTable(name)` is declared `table<string, table>`, so every row read out of a data
table is unchecked. But the codex already says which type lives in which table: a
registered game type declares `X.tableName = "name"`. This script reads those
declarations and emits one overload per type, e.g.

    ---@overload fun(tableName: "classes"): table<string, Class>

so `dmhub.GetTable("classes")`, `dmhub.GetTable(Class.tableName)` and a local holding the
literal all return typed rows. LuaLS infers `Class.tableName` as the literal, which is
what lets the second form match. A name that no type declares keeps the plain
`table<string, table>` signature, so nothing that checks today stops checking.

It writes two generated blocks, each between BEGIN/END marker lines:

- `Definitions/core-definitions.lua` (and, in a DMHub engine checkout, its source
  `Assets/CoreAssets/Lua/definitions/core-definitions.txt`, which a stub regen copies
  over it -- so both are kept in step): redeclarations of `dmhub.GetTable` and `dmhub.GetTableVisible` carrying the
  overloads. LuaLS merges them with the generated declarations in dmhub.lua. The
  TextAsset is documentation only; the engine never executes it.
- `DMHub Utils/TableCache.lua`: the same overloads as annotations on
  `GetTableCached`, whose inferred return is otherwise the untyped base signature.

Rules:
- only `X.tableName = "literal"` where X has a `@class` somewhere in the codex;
- a name claimed by several types maps to their union, except claims listed in
  IGNORE_CLAIMS (the abandoned JournalNode's share of `"documents"`);
- a type that declares several names gets one overload taking their union
  (`Background` is `"backgrounds"`, reassigned to `"careers"` by the MCDM rules);
- tests/, Definitions/ and the ignored folders are not scanned; `"none"` is skipped.

It rewrites each such type's `--- @field tableName string` to the literal it assigns
(`--- @field tableName "classes"`): a declared `string` widens `Class.tableName`, so no
overload matches it, and LuaLS then returns the union of every overload, which makes each
method call on the row a `self` mismatch.

It also gives each of those types `--- @field id string` in its own `@class` block (the
first one, by path, when a type is declared in several files), unless the type already
declares `id`. `LuaInterface.SetAndUploadTableItem` sets `item.id` (a new GUID when
absent) before any row is stored, so every row read back out of a table has one.

Re-run it after adding or renaming a `tableName`. It preserves each file's line endings.
"""
import collections, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
CODEX = os.path.normpath(os.path.join(HERE, '..', '..'))
CORE_MIRROR = os.path.join(CODEX, 'Definitions', 'core-definitions.lua')
TABLE_CACHE = os.path.join(CODEX, 'DMHub Utils', 'TableCache.lua')
# The engine-side source of core-definitions.lua; present only when the codex is checked
# out inside the DMHub engine repository.
ENGINE_CORE_DEFS = os.path.normpath(os.path.join(
    CODEX, '..', 'Assets', 'CoreAssets', 'Lua', 'definitions', 'core-definitions.txt'))

SKIP_DIRS = {'Definitions', 'tests', 'tools', '.claude', '.agents', '.git', 'compendium'}
SKIP_NAMES = {'none'}
BEGIN = '--- BEGIN generated by tools/typing/gen_table_overloads.py -- do not edit by hand'
END = '--- END generated by tools/typing/gen_table_overloads.py'
# Markers written before the script moved into the codex; recognised so they are replaced.
OLD_BEGIN = '--- BEGIN generated by tools/lua-typing/gen_table_overloads.py -- do not edit by hand'
OLD_END = '--- END generated by tools/lua-typing/gen_table_overloads.py'

assign_re = re.compile(r'''^\s*([A-Za-z_]\w*)\.tableName\s*=\s*(["'])([^"']+)\2''')
class_re = re.compile(r'^\s*---?\s*@class\s+([A-Za-z_][\w.]*)')
id_field_re = re.compile(r'^\s*---?\s*@field\s+id\??\s')
tablename_field_re = re.compile(r'^(\s*---?\s*@field\s+tableName\??\s+)(\S+)(.*)$')
# (type, name) claims to leave out. JournalNode ("DMHub Game Hud/Journal.lua") is an
# abandoned prototype -- its own header says "not much has been done on it yet" -- that
# happens to share the "documents" table; the rows there are CustomDocuments. Mapping the
# table to the union made every method call on a document a `self` mismatch.
IGNORE_CLAIMS = {('JournalNode', 'documents')}
ID_FIELD = '--- @field id string Key of this row in its data table; SetAndUploadTableItem sets it.'


def codex_files():
    for dirpath, dirnames, filenames in os.walk(CODEX):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for fn in sorted(filenames):
            if fn.endswith('.lua'):
                yield os.path.join(dirpath, fn)


def type_names():
    """type -> the table names it declares (after the ignore rules)."""
    names = collections.defaultdict(set)
    for name, types in scan().items():
        for t in types:
            names[t].add(name)
    return names


def class_block_edits():
    """{path: new bytes} for the two class-block edits:

    - `@field tableName <T>` becomes the literal the type assigns. A declared `string`
      widens `X.tableName` from its literal, so the overloads never match a call that
      passes it, and every such call returns the union of all of them.
    - `@field id string` is added to each table type that lacks one.
    """
    names = type_names()
    types = set(names)
    blocks = collections.defaultdict(list)   # type -> [(path, index of @class line)]
    has_id = set()
    files, retyped = {}, set()
    for path in codex_files():
        raw = open(path, 'rb').read()
        nl = '\r\n' if b'\r\n' in raw else '\n'
        L = raw.decode('utf-8', errors='replace').split(nl)
        for i, line in enumerate(L):
            m = class_re.match(line)
            if not m or m.group(1) not in types:
                continue
            t = m.group(1)
            blocks[t].append((path, i))
            literal = '|'.join(f'"{n}"' for n in sorted(names[t]))
            k = i + 1
            while k < len(L) and L[k].lstrip().startswith('--'):
                if id_field_re.match(L[k]):
                    has_id.add(t)
                fm = tablename_field_re.match(L[k])
                if fm and fm.group(2) != literal:
                    L[k] = fm.group(1) + literal + fm.group(3)
                    retyped.add(path)
                k += 1
        files[path] = (raw, nl, L)
        text = raw.decode('utf-8', errors='replace')
        for t in types:
            if re.search(rf'^\s*{re.escape(t)}\.id\s*=', text, re.M):
                has_id.add(t)
    inserts = collections.defaultdict(list)
    for t in sorted(types - has_id):
        if blocks[t]:
            path, i = blocks[t][0]
            inserts[path].append(i)
    out = {}
    for path in set(inserts) | retyped:
        raw, nl, L = files[path]
        L = list(L)
        for i in sorted(inserts.get(path, []), reverse=True):
            indent = L[i][:len(L[i]) - len(L[i].lstrip())]
            k = i + 1   # after the @class line and a typed `new`, when there is one
            if k < len(L) and re.match(r'^\s*---?\s*@field\s+new\b', L[k]):
                k += 1
            L.insert(k, indent + ID_FIELD)
        out[path] = nl.join(L).encode('utf-8')
    return out


def scan():
    classes, claims = set(), collections.defaultdict(set)
    for dirpath, dirnames, filenames in os.walk(CODEX):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for fn in filenames:
            if not fn.endswith('.lua'):
                continue
            with open(os.path.join(dirpath, fn), encoding='utf-8', errors='replace') as f:
                for line in f:
                    m = class_re.match(line)
                    if m:
                        classes.add(m.group(1))
                    m = assign_re.match(line)
                    if m and m.group(3) not in SKIP_NAMES:
                        if (m.group(1), m.group(3)) not in IGNORE_CLAIMS:
                            claims[m.group(3)].add(m.group(1))
    # name -> the declared types that claim it
    return {name: types & classes for name, types in claims.items() if types & classes}


def overload_lines(prefix=''):
    by_types = collections.defaultdict(set)
    for name, types in scan().items():
        by_types[tuple(sorted(types))].add(name)
    lines = []
    for types, names in sorted(by_types.items(), key=lambda kv: sorted(kv[1])[0].lower()):
        arg = '|'.join(f'"{n}"' for n in sorted(names))
        lines.append(f'{prefix}---@overload fun(tableName: {arg}): table<string, {"|".join(types)}>')
    return lines


def core_block():
    doc = [
        '--- Typed overloads for the data-table getters: each registered game type that declares',
        '--- `X.tableName = "name"` makes GetTable("name") return its rows as X. Merged by LuaLS',
        '--- with the declarations in dmhub.lua; names no type declares keep the plain signature.',
    ]
    out = [BEGIN]
    for fn in ('GetTable', 'GetTableVisible'):
        out += doc + overload_lines() + [
            '---@param tableName string',
            '---@return table<string, table>',
            f'function dmhub.{fn}(tableName) end',
            '',
        ]
    return out[:-1] + [END]


def cache_block():
    return [
        BEGIN,
        '--- Typed per table like dmhub.GetTable: rows of a table a game type declares with',
        '--- `X.tableName` come back as X.',
    ] + overload_lines() + [
        '---@param tableName string',
        '---@return table<string, table>',
        END,
    ]


def splice(path, block, anchor):
    """Replace the BEGIN..END block in path with block; with no block yet, insert it
    directly above the first line equal to anchor, or append when anchor is None."""
    raw = open(path, 'rb').read()
    nl = '\r\n' if b'\r\n' in raw else '\n'
    L = raw.decode('utf-8').split(nl)
    begin = BEGIN if BEGIN in L else OLD_BEGIN if OLD_BEGIN in L else None
    if begin is not None:
        i = L.index(begin)
        j = L.index(END if begin == BEGIN else OLD_END, i)
        L[i:j + 1] = block
    elif anchor is None:
        while L and L[-1] == '':
            L.pop()
        L += [''] + block + ['']
    else:
        i = L.index(anchor)
        L[i:i] = block
    return raw, nl.join(L).encode('utf-8')


def main():
    check = '--check' in sys.argv
    stale = []
    core_files = [CORE_MIRROR] + ([ENGINE_CORE_DEFS] if os.path.exists(ENGINE_CORE_DEFS) else [])
    edits = [splice(p, core_block(), None) for p in core_files]
    edits = [(p,) + e for p, e in zip(core_files, edits)]
    edits.append((TABLE_CACHE,) + splice(TABLE_CACHE, cache_block(), 'function GetTableCached(tableName)'))
    edits += [(p, open(p, 'rb').read(), new) for p, new in sorted(class_block_edits().items())]
    for path, old, new in edits:
        if old != new:
            stale.append(os.path.relpath(path, CODEX))
            if not check:
                open(path, 'wb').write(new)
    n = len(overload_lines())
    if check:
        print(f'{n} overloads; ' + ('stale: ' + ', '.join(stale) +
              ' -- run python tools/typing/gen_table_overloads.py' if stale else 'up to date'))
        return 1 if stale else 0
    print(f'{n} overloads; ' + ('wrote ' + ', '.join(stale) if stale else 'already up to date'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
