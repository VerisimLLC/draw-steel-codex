--Where tables were saved before the framework: one document, keyed by page + name.
local LEGACY_DOC = "tornpuzzles"
local ID_PREFIX = "t_"

function RichTornPuzzle.Create()
    return RichTornPuzzle.new{}
end

--First open of an old tag: copy its setup (stored on the tag) and its saved
--table (in the old shared document) into a framework puzzle.
---@param tag RichTornPuzzle
---@param id string|nil
local function Migrate(tag, id)
    if id == nil or Puzzle.Exists(id) then
        return
    end
    local config = {
        source = tag.source,
        image = tag.image or false,
        noteText = tag.noteText,
        paper = tag.paper,
        pieces = tostring(tag.pieces),
        pretape = tag.pretape,
        boardWidth = tag.boardWidth,
    }
    Puzzle.Create(id, "torn", config, tag.identifier and tostring(tag.identifier) or nil)

    local doc = tag:GetDocument()
    local docid = doc ~= nil and doc:try_get("id") or nil
    if docid == nil then
        return
    end
    local oldKey = Puzzle.SafeId(string.format("%s_%s", tostring(docid), tostring(tag.identifier or "default")))
    local board = Decode(mod:GetDocumentSnapshot(LEGACY_DOC).data[oldKey], PieceCount(config))
    if board ~= nil then
        Puzzle.ImportState(id, Encode(board),
            cond(board.done, { solved = true, solvedBy = "director", announced = true }, nil))
    end
end

function RichTornPuzzle.CreateDisplay(self)
    local m_token = nil
    local panel = Puzzle.CreatePanel(nil, {
        editing = function() return m_token ~= nil and m_token.editor == true end,
    })
    return gui.Panel{
        flow = "vertical",
        width = "auto",
        height = "auto",
        halign = "left",
        valign = "top",
        refreshTag = function(element, tag, match, token)
            self = tag or self
            m_token = token
            local id = Puzzle.JournalId(self, ID_PREFIX)
            Migrate(self, id)
            Puzzle.IndexJournal(self, id)
            panel:FireEvent("setPuzzle", id)
            panel:FireEvent("refreshPuzzleFrame")
        end,
        panel,
    }
end

function RichTornPuzzle.CreateEditor(self)
    return Puzzle.CreateEditor(function()
        local id = Puzzle.JournalId(self, ID_PREFIX)
        Migrate(self, id)
        return id
    end, function(id, typeid)
        Puzzle.Create(id, typeid, nil, self.identifier and tostring(self.identifier) or nil)
    end, function(tag) self = tag end)
end

