--Copy an encoded board into a state table field by field, so a save sends only
--the fields that changed.
---@param state table
---@param board TornBoard
local function StoreBoard(state, board)
    for k, v in pairs(Encode(board)) do
        state[k] = v
    end
end

--Holds are keyed per group with the framework's hold helper.
---@param groupId integer
---@return string
local function HoldKey(groupId)
    return "g" .. tostring(groupId)
end

--After a group is put down, join it to every neighbour it now lines up with.
--The group it lands against keeps its place, so a drop never yanks the table.
---@param board TornBoard
---@param shape TornShape
---@param groupId integer
---@return integer groupId the group the dropped pieces belong to now
---@return boolean joined
local function SnapGroup(board, shape, groupId)
    local joined = false
    local merged = true
    while merged do
        merged = false
        for _, seam in ipairs(shape.seams) do
            local ga, gb = board.member[seam.a], board.member[seam.b]
            if ga ~= gb and (ga == groupId or gb == groupId) then
                local other = cond(ga == groupId, gb, ga)
                local mine, theirs = board.groups[groupId], board.groups[other]
                if math.abs(mine.x - theirs.x) < SNAP_DISTANCE and math.abs(mine.y - theirs.y) < SNAP_DISTANCE then
                    theirs.z = math.max(mine.z, theirs.z)
                    MergeGroups(board, groupId, other)
                    groupId = other
                    joined = true
                    merged = true
                    break
                end
            end
        end
    end
    return groupId, joined
end

---@param board TornBoard
---@param shape TornShape
---@return integer taped
local function TapedSeams(board, shape)
    local taped = 0
    for _, seam in ipairs(shape.seams) do
        if board.member[seam.a] == board.member[seam.b] then
            taped = taped + 1
        end
    end
    return taped
end

---@param poly number[]
---@param x number
---@param y number
---@return boolean
local function PointInPolygon(poly, x, y)
    local inside = false
    local count = #poly // 2
    local j = count
    for i = 1, count do
        local xi, yi = poly[i * 2 - 1], poly[i * 2]
        local xj, yj = poly[j * 2 - 1], poly[j * 2]
        if (yi > y) ~= (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi then
            inside = not inside
        end
        j = i
    end
    return inside
end

---@param ctx PuzzleContext
---@return Panel
local function Render(ctx)
    local m_ctx = ctx
    local m_aspect = 1
    local m_imageInfoFor = nil
    local m_imageSize = nil
    local m_board = nil ---@type TornBoard|nil
    local m_shape = nil ---@type TornShape|nil

    --layout in pixels, recomputed every refresh
    local m_imageW, m_imageH, m_tableW, m_tableH = 1, 1, 1, 1

    --interaction state, local to this client
    local m_pressGroup = nil ---@type integer|nil
    local m_dragGroup = nil ---@type integer|nil
    local m_dragX, m_dragY = 0, 0

    local m_piecePanels = {} ---@type Panel[]
    local m_tapePanels = {} ---@type table<integer, Panel>
    local m_builtFor = nil

    local resultPanel
    local table_
    local placeholder
    local holdLabel
    local cleanCopyButton
    local Refresh

    --Typed notes: the locally rendered image, the text+paper it was rendered from,
    --a render in flight (its key), and the rendered note's height/width.
    local m_noteImage = nil ---@type string|nil
    local m_noteKey = nil ---@type string|nil
    local m_noteRequested = nil ---@type string|nil
    local m_noteAspect = 1

    local function Config()
        return m_ctx.config
    end

    local function IsNote()
        return Config().source == "note"
    end

    local function NotePaper()
        return NOTE_PAPERS[Config().paper] or NOTE_PAPERS.letter
    end

    --The picked-up group, from the framework's click-to-place helper.
    ---@return integer|nil
    local function Selected()
        local key = m_ctx:Picked()
        if key == nil then
            return nil
        end
        return math.tointeger(tonumber(string.sub(key, 2)))
    end

    --What the pieces are cut from: the uploaded image, or the rendered note. A note
    --keeps showing its previous render while an edited version renders.
    ---@return string|nil
    local function CurrentImage()
        if IsNote() then
            return m_noteImage
        end
        return Config().image or nil
    end

    local function Interactive()
        return not m_ctx.readonly and CurrentImage() ~= nil
    end

    --The group another player holds, and their name.
    ---@param board TornBoard
    ---@return integer|nil groupId, string|nil name
    local function OthersHold(board)
        for id in pairs(board.groups) do
            local name = m_ctx:HeldBy(HoldKey(id))
            if name ~= nil then
                return id, name
            end
        end
        return nil, nil
    end

    --Render the note (if its text or paper changed since the last render) on this
    --client. When it lands, the table re-lays out around the new image; the tear and
    --the table's progress are untouched because pieces sit in image-relative units.
    local function RequestNote()
        local text = Config().noteText or ""
        if not IsNote() or text == "" or not NotesSupported() then
            return
        end
        local paper = NotePaper()
        local key = string.format("%s|%s", tostring(Config().paper), text)
        if key == m_noteKey or key == m_noteRequested then
            return
        end
        m_noteRequested = key

        local width, height, fontSize = NoteLayout(text, paper)
        ---@diagnostic disable-next-line: undefined-field -- engine API newer than the Definitions stubs
        gui.RenderToImage{
            panel = gui.Panel{
                width = width,
                height = height,
                bgimage = "panels/square.png",
                bgcolor = paper.paper,
                gui.Label{
                    text = text,
                    fontFace = paper.font,
                    fontSize = fontSize,
                    color = paper.ink,
                    width = width - NOTE_PADDING * 2,
                    height = "auto",
                    halign = "center",
                    valign = "center",
                    textAlignment = paper.align,
                },
            },
            width = width,
            height = height,
            scale = NOTE_RENDER_SCALE,
            complete = function(imageid)
                --a newer edit superseded this render; its own render will land.
                if mod.unloaded or not resultPanel.valid or m_noteRequested ~= key then
                    return
                end
                m_noteImage, m_noteKey, m_noteRequested = imageid, key, nil
                m_noteAspect = height / width
                Refresh()
            end,
            error = function(message)
                --leave m_noteRequested set so a failing note is not retried every refresh.
                print("TornPuzzle: could not render the note:", message)
            end,
        }
    end

    local function RequestImageShape()
        if IsNote() then
            --a rendered note's shape is known exactly; no image query needed.
            m_imageInfoFor = nil
            m_aspect = m_noteAspect
            m_imageSize = { width = NOTE_WIDTH * NOTE_RENDER_SCALE, height = math.floor(NOTE_WIDTH * m_noteAspect) * NOTE_RENDER_SCALE }
            return
        end
        local image = Config().image
        if image == m_imageInfoFor then
            return
        end
        m_imageInfoFor = image
        m_aspect = 1
        m_imageSize = nil
        if not image then
            return
        end
        --GetImageInfo can call back more than once; only the latest image counts.
        dmhub.GetImageInfo(image, function(info)
            if mod.unloaded or not resultPanel.valid or image ~= Config().image then
                return
            end
            if info ~= nil and info.width ~= nil and info.width > 0 then
                m_aspect = info.height / info.width
                m_imageSize = { width = info.width, height = info.height }
                Refresh()
            end
        end)
    end

    --(Re)create the piece panels when the tear pattern changes. Pieces never take
    --clicks themselves: their transparent corners would steal grabs, so the table
    --hit-tests outlines instead (see PieceAt).
    local function BuildPieces(board, shape)
        local key = string.format("%d:%d:%s", board.n, board.variant, tostring(board.mirror))
        if m_builtFor == key then
            return
        end
        m_builtFor = key
        m_piecePanels = {}
        m_tapePanels = {}
        for k = 1, board.n do
            m_piecePanels[k] = gui.Panel{
                bgimage = "panels/square.png",
                bgcolor = "white",
                halign = "left",
                valign = "top",
                interactable = false,
            }
        end
        for i = 1, #shape.seams do
            m_tapePanels[i] = gui.Panel{
                classes = {"hidden"},
                bgimage = "panels/square.png",
                --masking-tape beige with a faint dark edge: the edge keeps it visible on
                --pale parchment and white paper, where a near-white strip disappeared.
                bgcolor = "#d8c79bd9",
                border = 1,
                borderColor = "#3a2a1a40",
                halign = "left",
                valign = "top",
                interactable = false,
                --fade is tracked in data: reading a selfStyle value that was never
                --set throws, so selfStyle.opacity cannot be the source of truth.
                data = { shown = false, fade = 1 },
                --a new strip fades in rather than popping.
                thinkTime = 0.03,
                think = function(element)
                    if element.data.fade < 1 then
                        element.data.fade = math.min(1, element.data.fade + 0.12)
                        element.selfStyle.opacity = element.data.fade
                    end
                end,
            }
        end
        --every panel lives on the table from the start (unused tape just hidden);
        --the engine flags panels that are created but never given a parent.
        local children = {}
        for _, panel in ipairs(m_piecePanels) do
            children[#children + 1] = panel
        end
        for _, panel in ipairs(m_tapePanels) do
            children[#children + 1] = panel
        end
        children[#children + 1] = holdLabel
        table_.children = children
    end

    --Place every piece and tape strip. The group being dragged is offset by the
    --drag so far; everything else sits where the board says.
    local function Layout()
        local board, shape = m_board, m_shape
        if board == nil or shape == nil then
            return
        end
        local othersGroup, othersName = OthersHold(board)
        local selected = Selected()

        --draw order: groups by z, the dragged/selected group on top.
        local order = {}
        for id, group in pairs(board.groups) do
            order[#order + 1] = { id = id, z = group.z }
        end
        table.sort(order, function(a, b)
            local az = cond(a.id == m_dragGroup or a.id == selected, math.huge, a.z)
            local bz = cond(b.id == m_dragGroup or b.id == selected, math.huge, b.z)
            if az == bz then
                return a.id < b.id
            end
            return az < bz
        end)

        local groupSize = {}
        for _, g in ipairs(board.member) do
            groupSize[g] = (groupSize[g] or 0) + 1
        end

        local children = {}
        for _, entry in ipairs(order) do
            local id = entry.id
            local group = board.groups[id]
            local ox, oy = group.x * m_imageW, group.y * m_imageH
            if id == m_dragGroup then
                ox, oy = ox + m_dragX, oy + m_dragY
            end
            local lifted = id == m_dragGroup or id == selected
            if lifted then
                --a picked-up group rises off the table so it reads as "in hand".
                oy = oy - 8
            end
            local heldByOther = othersGroup == id

            for k, g in ipairs(board.member) do
                if g == id then
                    local piece = shape.pieces[k]
                    local b = piece.bbox
                    local panel = m_piecePanels[k]
                    panel.bgimage = CurrentImage()
                    panel.bgimageMask = shape.atlas
                    panel.bgimageMaskRect = piece.mask
                    panel.selfStyle.imageRect = { x1 = b[1], x2 = b[3], y1 = 1 - b[4], y2 = 1 - b[2] }
                    panel.selfStyle.x = ox + b[1] * m_imageW
                    panel.selfStyle.y = oy + b[2] * m_imageH
                    panel.selfStyle.width = (b[3] - b[1]) * m_imageW
                    panel.selfStyle.height = (b[4] - b[2]) * m_imageH
                    --loose pieces keep their tilt until picked up.
                    panel.selfStyle.rotate = cond(groupSize[id] == 1 and not lifted, group.tilt, 0)
                    --only a lone piece grows when lifted: scaling each piece of a
                    --joined group about its own centre would open gaps at the seams.
                    panel.selfStyle.scale = cond(lifted and groupSize[id] == 1, 1.08, 1)
                    panel.selfStyle.opacity = cond(heldByOther, 0.6, 1)
                    children[#children + 1] = panel
                end
            end

            for i, seam in ipairs(shape.seams) do
                if board.member[seam.a] == id and board.member[seam.b] == id then
                    local tape = m_tapePanels[i]
                    --tape length follows the image size; it crosses the seam at right angles.
                    local len = math.max(22, math.min(64, 0.11 * math.min(m_imageW, m_imageH)))
                    local wid = len * 0.34
                    local rad = math.rad(seam.angle)
                    local seamAngle = math.deg(math.atan(math.sin(rad) * m_imageH, math.cos(rad) * m_imageW))
                    --a little per-seam jitter so strips look hand-laid.
                    local jitter = ((i * 37) % 17) - 8
                    tape.selfStyle.width = len
                    tape.selfStyle.height = wid
                    tape.selfStyle.x = ox + seam.mid[1] * m_imageW - len / 2
                    tape.selfStyle.y = oy + seam.mid[2] * m_imageH - wid / 2
                    tape.selfStyle.rotate = -(seamAngle + 90) + jitter
                    if not tape.data.shown then
                        tape.data.shown = true
                        tape.data.fade = 0
                        tape.selfStyle.opacity = 0
                    end
                    tape:SetClass("hidden", false)
                    children[#children + 1] = tape
                end
            end
        end

        --tape on seams that are no longer joined (after a reset) disappears.
        for i, seam in ipairs(shape.seams) do
            local tape = m_tapePanels[i]
            if board.member[seam.a] ~= board.member[seam.b] and tape ~= nil then
                tape.data.shown = false
                tape:SetClass("hidden", true)
                children[#children + 1] = tape
            end
        end

        children[#children + 1] = holdLabel
        table_.children = children

        if othersGroup ~= nil and board.groups[othersGroup] ~= nil then
            local group = board.groups[othersGroup]
            local x1, y1 = GroupBounds(board, shape, othersGroup)
            holdLabel.text = string.format("%s is holding this", othersName)
            holdLabel.selfStyle.x = (group.x + x1) * m_imageW
            holdLabel.selfStyle.y = math.max(0, (group.y + y1) * m_imageH - 20)
            holdLabel:SetClass("hidden", false)
        else
            holdLabel:SetClass("hidden", true)
        end
    end

    Refresh = function()
        if not resultPanel.valid then
            return
        end
        RequestNote()
        RequestImageShape()

        local hasImage = CurrentImage() ~= nil
        table_:SetClass("collapsed", not hasImage)
        --a note that is just rendering shows nothing; one that cannot render says why.
        local placeholderText = nil
        if not hasImage then
            if not IsNote() then
                placeholderText = "Torn puzzle: choose an image in the annotations strip below."
            elseif not NotesSupported() then
                placeholderText = "This note needs a newer version of the Codex."
            elseif (Config().noteText or "") == "" then
                placeholderText = "Torn puzzle: write the note in the puzzle's settings."
            end
        end
        if placeholderText ~= nil then
            placeholder.text = placeholderText
        end
        placeholder:SetClass("collapsed", placeholderText == nil)
        if not hasImage or m_ctx.state == nil then
            cleanCopyButton:SetClass("collapsed", true)
            return
        end

        local n = PieceCount(Config())
        local board = Decode(m_ctx.state, n)
        if board == nil then
            return
        end
        local shape = ShapeFor(board)
        m_board, m_shape = board, shape
        --a pick or drag whose group vanished (merged by someone else) is dropped.
        local selected = Selected()
        if selected ~= nil and board.groups[selected] == nil then
            m_ctx:Unpick()
        end
        if m_dragGroup ~= nil and board.groups[m_dragGroup] == nil then
            m_dragGroup = nil
        end

        local aspect = math.max(0.4, math.min(2.5, m_aspect))
        m_tableW = tonumber(Config().boardWidth) or 640
        m_imageW = m_tableW / TABLE_SCALE
        m_imageH = m_imageW * aspect
        m_tableH = m_imageH * TABLE_SCALE
        table_.selfStyle.width = m_tableW
        table_.selfStyle.height = m_tableH
        resultPanel.selfStyle.width = m_tableW

        BuildPieces(board, shape)
        Layout()
        cleanCopyButton:SetClass("collapsed", not (board.done or m_ctx.solved))
    end

    --The group whose piece outline is under a table-pixel point, topmost first.
    ---@param px number
    ---@param py number
    ---@return integer|nil
    local function PieceAt(px, py)
        local board, shape = m_board, m_shape
        if board == nil or shape == nil then
            return nil
        end
        local order = {}
        for id, group in pairs(board.groups) do
            order[#order + 1] = { id = id, z = group.z }
        end
        table.sort(order, function(a, b) return a.z > b.z end)

        local groupSize = {}
        for _, g in ipairs(board.member) do
            groupSize[g] = (groupSize[g] or 0) + 1
        end

        for _, entry in ipairs(order) do
            local group = board.groups[entry.id]
            for k, g in ipairs(board.member) do
                if g == entry.id then
                    local b = shape.pieces[k].bbox
                    local x, y = px, py
                    if groupSize[g] == 1 and group.tilt ~= 0 then
                        --undo the piece's tilt (counter-clockwise on screen) about its centre.
                        local cx = (group.x + (b[1] + b[3]) / 2) * m_imageW
                        local cy = (group.y + (b[2] + b[4]) / 2) * m_imageH
                        local t = math.rad(group.tilt)
                        local dx, dy = x - cx, y - cy
                        x = cx + dx * math.cos(t) - dy * math.sin(t)
                        y = cy + dx * math.sin(t) + dy * math.cos(t)
                    end
                    local ux = x / m_imageW - group.x
                    local uy = y / m_imageH - group.y
                    if ux >= b[1] and ux <= b[3] and uy >= b[2] and uy <= b[4]
                        and PointInPolygon(shape.pieces[k].poly, ux, uy) then
                        return entry.id
                    end
                end
            end
        end
        return nil
    end

    ---@return number px, number py
    local function MouseOnTable()
        local point = table_.mousePoint
        return point.x * m_tableW, (1 - point.y) * m_tableH
    end

    --Put a group down at a new origin and join it to any neighbours it now lines
    --up with. The framework notices the finished note and announces it.
    ---@param groupId integer
    ---@param x number
    ---@param y number
    local function PlaceGroup(groupId, x, y)
        m_ctx:Change(function(state, config)
            local board = Decode(state, PieceCount(config))
            if board == nil or board.groups[groupId] == nil then
                return false
            end
            local shape = ShapeFor(board)
            local group = board.groups[groupId]
            group.x, group.y = x, y
            group.tilt = 0
            group.z = TopZ(board) + 1
            --snap BEFORE clamping: a neighbour's matching spot can hang off the table
            --edge, and clamping first made that join impossible. The joined group is
            --then nudged back onto the table as a whole.
            local merged = SnapGroup(board, shape, groupId)
            ClampGroup(board, shape, merged)
            if not board.done and GroupCount(board) == 1 then
                board.done = true
                local only = next(board.groups)
                if only ~= nil then
                    local offset = (TABLE_SCALE - 1) / 2
                    board.groups[only].x, board.groups[only].y = offset, offset
                end
            end
            StoreBoard(state, board)
        end, "Move torn puzzle piece")
        m_ctx:Release(HoldKey(groupId))
    end

    holdLabel = gui.Label{
        classes = {"hidden", "sizeXs"},
        width = "auto",
        height = "auto",
        halign = "left",
        valign = "top",
        bgimage = "panels/square.png",
        bgcolor = "#000000aa",
        hpad = 4,
        borderBox = true,
        interactable = false,
        text = "",
    }

    table_ = gui.Panel{
        flow = "none",
        width = 640,
        height = 640,
        halign = "left",
        bgimage = "panels/square.png",
        bgcolor = "#ffffff0d",
        border = 1,
        borderColor = "#ffffff26",
        draggable = true,
        dragMove = false,

        press = function(element)
            m_pressGroup = nil
            if not Interactive() or m_board == nil or m_board.done then
                return
            end
            local px, py = MouseOnTable()
            m_pressGroup = PieceAt(px, py)
        end,

        beginDrag = function(element)
            m_dragGroup = nil
            local groupId = m_pressGroup
            if groupId == nil or m_board == nil or m_board.done then
                return
            end
            if Selected() ~= nil then
                m_ctx:Unpick()
            end
            if not m_ctx:Hold(HoldKey(groupId)) then
                return
            end
            m_dragGroup = groupId
            m_dragX, m_dragY = 0, 0
        end,

        dragging = function(element, target)
            if m_dragGroup == nil then
                return
            end
            m_dragX, m_dragY = element.dragDelta.x, element.dragDelta.y
            Layout()
        end,

        drag = function(element, target)
            local groupId = m_dragGroup
            if groupId == nil or m_board == nil then
                return
            end
            local group = m_board.groups[groupId]
            local dx, dy = element.dragDelta.x, element.dragDelta.y
            m_dragGroup = nil
            if group == nil then
                m_ctx:Release(HoldKey(groupId))
                Refresh()
                return
            end
            PlaceGroup(groupId, group.x + dx / m_imageW, group.y + dy / m_imageH)
        end,

        --The no-drag path: click a piece to pick it up, then click where it goes.
        click = function(element)
            if not Interactive() or m_board == nil or m_board.done then
                return
            end
            local px, py = MouseOnTable()
            local hit = PieceAt(px, py)
            local selected = Selected()
            if selected == nil then
                if hit == nil then
                    return
                end
                m_ctx:Pick(HoldKey(hit))
                Layout()
                return
            end
            if hit == selected then
                m_ctx:Unpick()
                Refresh()
                return
            end
            --centre the picked-up group on the clicked point.
            local x1, y1, x2, y2 = GroupBounds(m_board, ShapeFor(m_board), selected)
            m_ctx:Unpick()
            PlaceGroup(selected, px / m_imageW - (x1 + x2) / 2, py / m_imageH - (y1 + y2) / 2)
        end,

        holdLabel,
    }

    placeholder = gui.Label{
        classes = {"collapsed", "sizeS", "bordered"},
        width = 340,
        height = 64,
        halign = "left",
        textAlignment = "center",
        text = "",
    }

    cleanCopyButton = gui.Button{
        classes = {"sizeXs", "collapsed"},
        text = "View clean copy",
        width = 120,
        height = 22,
        vmargin = 2,
        halign = "left",
        press = function(element)
            local image = CurrentImage()
            if image == nil then
                return
            end
            local size = m_imageSize or { width = 1024, height = 1024 }
            GameHud.instance:ViewCompendiumEntryModal(ImageDocument.new{
                imageid = image,
                width = size.width,
                height = size.height,
            })
        end,
    }

    resultPanel = gui.Panel{
        flow = "vertical",
        width = 640,
        height = "auto",
        halign = "left",
        refreshPuzzle = function(element, newCtx)
            m_ctx = newCtx
            --a remote write mid-drag would snap the held pieces back; wait for the drop.
            if m_dragGroup == nil then
                Refresh()
            end
        end,
        table_,
        placeholder,
        cleanCopyButton,
    }
    return resultPanel
end

